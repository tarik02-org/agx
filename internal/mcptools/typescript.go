package mcptools

import (
	_ "embed"
	"encoding/json"
	"slices"
	"strings"
)

// Server is an MCP server as the generated client sees it.
type Server struct {
	ID          string
	Description string
	// Environment names the variables the server's values read, which the client forwards
	// outside a launch.
	Environment []string
	Tools       []Tool
}

// Tool is one tool of a Server.
type Tool struct {
	Name        string
	Description string
	Input       *Schema
	// Output is nil when the tool declares no structured result.
	Output *Schema
}

//go:embed client.mjs
var clientRuntime string

//go:embed client.d.mts
var clientTypes string

// Declarations renders TypeScript declarations for the client Client generates: the shared
// types, and a typed function per tool, grouped by server.
func Declarations(servers []Server) string {
	var b strings.Builder
	b.WriteString("// Generated by agx mcp types; regenerate it when servers change.\n\n")
	b.WriteString(clientTypes)
	b.WriteString("\nexport declare const servers: {\n")
	for _, s := range servers {
		b.WriteString(docComment(s.Description, "  "))
		b.WriteString("  " + propertyName(s.ID) + ": {\n")
		for _, t := range s.Tools {
			b.WriteString(docComment(t.Description, "    "))
			b.WriteString("    " + propertyName(t.Name) + "(" + parameters(t.Input))
			b.WriteString("options?: CallOptions): Promise<CallResult<")
			if t.Output != nil {
				b.WriteString(renderer{root: t.Output, indent: "  "}.typeOf(t.Output, 2))
			} else {
				b.WriteString("unknown")
			}
			b.WriteString(">>;\n")
		}
		b.WriteString("  };\n")
	}
	b.WriteString("};\n")
	for _, s := range servers {
		if exportable(s.ID) {
			b.WriteString("export declare const " + s.ID + ": (typeof servers)[" + quote(s.ID) + "];\n")
		}
	}
	return b.String()
}

// parameters renders a tool's arguments parameter, optional when no argument is required.
func parameters(input *Schema) string {
	r := renderer{root: input, indent: "  "}
	s := r.resolve(input)
	if s == nil || len(s.Properties) == 0 {
		return "args?: Record<string, unknown>, "
	}
	optional := "?"
	if len(s.Required) > 0 {
		optional = ""
	}
	return "args" + optional + ": " + r.typeOf(s, 2) + ", "
}

// Client renders the ES module that calls tools through the daemon whose discovery file is
// discovery. all makes it reach every configured server, as --all does, instead of a launch's
// or the working directory's.
func Client(servers []Server, discovery string, all bool) string {
	var b strings.Builder
	b.WriteString("// Generated by agx mcp types; regenerate it when servers change.\n")
	b.WriteString("const discovery = " + quote(discovery) + ";\n")
	b.WriteString("const all = " + boolText(all) + ";\n")
	environment := map[string][]string{}
	for _, s := range servers {
		environment[s.ID] = append([]string{}, s.Environment...)
	}
	encoded, _ := json.Marshal(environment)
	b.WriteString("const environment = " + string(encoded) + ";\n\n")
	b.WriteString(clientRuntime)
	b.WriteString("\nexport const servers = {\n")
	for _, s := range servers {
		names := []string{}
		for _, t := range s.Tools {
			names = append(names, t.Name)
		}
		encoded, _ := json.Marshal(names)
		b.WriteString("  " + quote(s.ID) + ": server(" + quote(s.ID) + ", " + string(encoded) + "),\n")
	}
	b.WriteString("};\n")
	for _, s := range servers {
		if exportable(s.ID) {
			b.WriteString("export const " + s.ID + " = servers[" + quote(s.ID) + "];\n")
		}
	}
	return b.String()
}

func quote(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func boolText(v bool) string {
	if v {
		return "true"
	}
	return "false"
}

// exportable reports whether a server ID can be a named export: an identifier that is no
// reserved word and does not clash with the module's own exports.
func exportable(id string) bool {
	return identifier(id) && !slices.Contains(reserved, id)
}

var reserved = []string{
	"AgxError", "call", "servers",
	"await", "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete",
	"do", "else", "enum", "export", "extends", "false", "finally", "for", "function", "if", "implements",
	"import", "in", "instanceof", "interface", "let", "new", "null", "package", "private", "protected",
	"public", "return", "static", "super", "switch", "this", "throw", "true", "try", "typeof", "var",
	"void", "while", "with", "yield", "arguments", "eval",
}
